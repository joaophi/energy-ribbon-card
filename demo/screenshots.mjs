// Renders every demo scenario (light and dark) to docs/screenshots/ and rewrites the README gallery.
// Needs `npm run demo` first and Playwright's Chromium; see README → Development.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { chromium } from "playwright";

const root = new URL("..", import.meta.url).pathname;
const RAW = "https://raw.githubusercontent.com/joaophi/energy-ribbon-card/master/docs/screenshots";
mkdirSync(`${root}docs/screenshots`, { recursive: true });

const browser = await chromium.launch();
let cards = [];
for (const theme of ["light", "dark"]) {
  const page = await browser.newPage({ colorScheme: theme, deviceScaleFactor: 2, viewport: { width: 480, height: 1000 } });
  page.on("pageerror", (e) => {
    throw e;
  });
  await page.goto(`file://${root}docs/index.html?shot=all&w=400`, { waitUntil: "networkidle" });
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(300);
  cards = await page.$$eval(".ha-card", (els) =>
    els.map((el) => ({
      id: el.id,
      slug: el.dataset.slug,
      title: el.querySelector("h2").textContent,
      note: el.querySelector(".note").textContent,
    }))
  );
  for (const c of cards) {
    await page.locator(`#${c.id}`).screenshot({ path: `${root}docs/screenshots/${c.slug}-${theme}.png`, omitBackground: true });
  }
}
await browser.close();

const cell = (c) =>
  c
    ? `<td width="50%" valign="top">
<picture>
<source media="(prefers-color-scheme: dark)" srcset="${RAW}/${c.slug}-dark.png">
<img alt="${c.title}" src="${RAW}/${c.slug}-light.png">
</picture>
<br><b>${c.title}</b><br><sub>${c.note}</sub>
</td>`
    : "<td></td>";
const rows = [];
for (let i = 0; i < cards.length; i += 2) rows.push(`<tr>\n${cell(cards[i])}\n${cell(cards[i + 1])}\n</tr>`);
const gallery = `<!-- gallery:start (generated by demo/screenshots.mjs) -->\n<table>\n${rows.join("\n")}\n</table>\n<!-- gallery:end -->`;
const readme = readFileSync(`${root}README.md`, "utf8");
writeFileSync(`${root}README.md`, readme.replace(/<!-- gallery:start[\s\S]*?<!-- gallery:end -->/, gallery));
console.log(`${cards.length} scenarios rendered`);
